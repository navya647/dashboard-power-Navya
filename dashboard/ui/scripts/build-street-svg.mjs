// Generates src/lib/streetSvg.generated.ts from scripts/street-scene.js.
//
// street-scene.js is the artwork source for the landing page's animated street (the same builder
// as the standalone prototype in D:\power dashboard\animated-hero). It writes its SVG into
// document.getElementById('scene').innerHTML, so this runs it against a tiny fake DOM, captures
// that markup, and saves it as a string constant. Static, deterministic markup means the server
// and client render identical HTML, so there are no hydration mismatches.
//
// Run after editing street-scene.js:  node scripts/build-street-svg.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
let markup = '';
const fakeSvg = {
  querySelector: () => null,
  set innerHTML(html) { markup = html; },
};
globalThis.document = { getElementById: () => fakeSvg };
new Function(readFileSync(join(here, 'street-scene.js'), 'utf8'))();
if (!markup) throw new Error('street-scene.js produced no markup');

// collapse the template-literal indentation so the bundle stays small
markup = markup.replace(/\n\s+/g, ' ');
const out = `// GENERATED by scripts/build-street-svg.mjs from scripts/street-scene.js. Do not edit by hand.
export const STREET_SVG = ${JSON.stringify(markup)};
`;
writeFileSync(join(here, '..', 'src', 'lib', 'streetSvg.generated.ts'), out);
console.log(`wrote streetSvg.generated.ts (${(out.length / 1024).toFixed(1)} KB)`);
